// Velocity (PaperMC). Downloaded from the Paper fill API, launched on Java 25 with the identical
// headline JVM flags, modern forwarding, and per-IP login rate limiting off. Velocity prints the
// transport, compressor and cipher it loaded on one start-up line, which the fairness check reads;
// a run where that line does not confirm libdeflate and epoll is marked unfair rather than compared.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { JVM_HEADLINE_FLAGS } from './index.js';
import { Proxy } from './base.js';
import { download, findJava } from '../reuse.js';

export class VelocityProxy extends Proxy {
  get forwarding() {
    return 'modern';
  }

  async spawnSpec() {
    this.nativeChecks = [
      { label: 'transport', pattern: /will use \{?epoll/, required: true },
      { label: 'compression', pattern: /compression/i, required: false },
    ];
    this.stopCommand = 'shutdown';
    this.failurePatterns = [/Unable to start Velocity/i];
    const dir = this.freshWorkDir();
    const jar = await download(this.spec.url, join(this.cacheDir, 'proxies', `velocity-${this.spec.version}-${this.spec.build}.jar`), { sha256: this.spec.sha256 });
    writeFileSync(join(dir, 'velocity.toml'), this.config());
    writeFileSync(join(dir, 'forwarding.secret'), this.secret);
    // An empty plugins dir keeps Velocity from scanning anything.
    mkdirSync(join(dir, 'plugins'), { recursive: true });
    const java = await findJava(this.spec.java, this.cacheDir);
    return {
      command: java,
      args: [...JVM_HEADLINE_FLAGS, '-jar', jar],
      env: {},
    };
  }

  config() {
    const servers = Object.entries(this.backends)
      .map(([name, port]) => `${name} = "127.0.0.1:${port}"`)
      .join('\n');
    const order = Object.keys(this.backends)
      .map((s) => `"${s}"`)
      .join(', ');
    return `# Generated by bench/src/proxies/velocity.js
config-version = "2.7"
bind = "127.0.0.1:${this.port}"
online-mode = false
player-info-forwarding-mode = "modern"
forwarding-secret-file = "forwarding.secret"
announce-forge = false
kick-existing-players = false
ping-passthrough = "DISABLED"
show-ping-requests = false

[servers]
${servers}
try = [${order}]

[advanced]
compression-threshold = ${this.compressionThreshold}
compression-level = ${this.compressionLevel}
login-ratelimit = 0
connection-timeout = 5000
read-timeout = 30000
tcp-fast-open = false

[query]
enabled = false
`;
  }
}
