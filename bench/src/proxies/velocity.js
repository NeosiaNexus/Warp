// Velocity (PaperMC). Downloaded from the Paper fill API, launched on Java 25 with the identical
// headline JVM flags, modern forwarding, and per-IP login rate limiting off. Velocity prints the
// transport, compressor and cipher it loaded on one start-up line, which the fairness check reads;
// a run where that line does not confirm libdeflate and epoll is marked unfair rather than compared.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { JVM_HEADLINE_FLAGS } from './index.js';
import { Proxy } from './base.js';
import { download, findJava } from '../reuse.js';

export class VelocityProxy extends Proxy {
  get forwarding() {
    return 'modern';
  }

  // One line: "Connections will use epoll channels, libdeflate (Linux x86_64) compression, OpenSSL
  // 3.x.x (Linux x86_64) ciphers". The fallback reads "Java compression, Java ciphers", so the
  // compression pattern must name libdeflate: matching the word "compression" alone would confirm
  // the fallback. Ciphers are reported but not required: offline mode never encrypts a connection.
  get nativeChecks() {
    return [
      { label: 'transport', pattern: /will use \{?epoll/, required: true },
      { label: 'compression', pattern: /libdeflate[^,]*compression/, required: true },
      { label: 'cipher', pattern: /OpenSSL[^,]*ciphers?|native[^,]*ciphers?/, required: false },
    ];
  }

  get protectionPatterns() {
    return [/rate.?limit/i];
  }

  async spawnSpec() {
    this.stopCommand = 'shutdown';
    this.failurePatterns = [/Unable to start Velocity/i];
    const dir = this.freshWorkDir();
    const jar = await download(this.spec.url, join(this.cacheDir, 'proxies', `velocity-${this.spec.version}-${this.spec.build}.jar`), { sha256: this.spec.sha256 });
    writeFileSync(join(dir, 'velocity.toml'), this.config());
    writeFileSync(join(dir, 'forwarding.secret'), this.secret);
    // No plugins, and bStats telemetry off (its opt-out lives in plugins/bStats/config.txt).
    mkdirSync(join(dir, 'plugins', 'bStats'), { recursive: true });
    writeFileSync(join(dir, 'plugins', 'bStats', 'config.txt'), 'enabled=false\nserverUuid=00000000-0000-0000-0000-000000000000\nlogFailedRequests=false\n');
    // A full JDK, not a JRE: the harness reads the live heap with its jcmd (heap.js).
    const java = await findJava(this.spec.java, this.cacheDir, { tools: true });
    this.javaPath = java;
    return {
      command: java,
      // Decode failures name the packet instead of a generic error: diagnostics only, no cost otherwise.
      args: [...JVM_HEADLINE_FLAGS, '-Dvelocity.packet-decode-logging=true', '-jar', jar],
      env: {},
    };
  }

  config() {
    const servers = Object.entries(this.backends)
      .map(([name, port]) => `${name} = "127.0.0.1:${port}"`)
      .join('\n');
    const order = Object.keys(this.backends)
      .map((s) => `"${s}"`)
      .join(', ');
    return `# Generated by bench/src/proxies/velocity.js
config-version = "2.7"
bind = "127.0.0.1:${this.port}"
online-mode = false
player-info-forwarding-mode = "modern"
forwarding-secret-file = "forwarding.secret"
announce-forge = false
kick-existing-players = false
ping-passthrough = "DISABLED"
show-ping-requests = false

[servers]
${servers}
try = [${order}]

# Empty on purpose: without this table Velocity fills in its example forced hosts, which point
# at servers that do not exist here and make the configuration invalid.
[forced-hosts]

[advanced]
compression-threshold = ${this.compressionThreshold}
compression-level = ${this.compressionLevel}
login-ratelimit = 0
connection-timeout = 5000
read-timeout = 30000
tcp-fast-open = false

[query]
enabled = false
`;
  }
}
