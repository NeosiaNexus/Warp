// Gate (minekube), a Go proxy. Downloaded as a pinned linux-amd64 binary, verified, and run with
// Go runtime defaults (GOMAXPROCS follows the cpuset, so taskset bounds its parallelism the same way
// it bounds a JVM proxy). Two shapes share this adapter: full Gate (id "gate", servers plus switching
// and the /server command) and Gate Lite (id "gatelite", a reverse proxy that only pipes bytes and
// routes by virtual host). Lite is a different workload class, so the report labels it separately and
// never treats it as a Velocity peer.
//
// Go has no compression or cipher natives: it uses the standard library's compress/zlib. That is
// stated in the report rather than flagged as a missing native, since there is nothing to load.
import { chmodSync, copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { Proxy } from './base.js';
import { download } from '../reuse.js';

export class GateProxy extends Proxy {
  get lite() {
    return this.id === 'gatelite';
  }

  // Gate (full) uses Velocity modern forwarding to the backends; Lite does not forward player info.
  get forwarding() {
    return this.lite ? 'none' : 'modern';
  }

  // Nothing native to confirm: the report prints "none to check" for a proxy with no required line.
  get nativeChecks() {
    return [{ label: 'listening', pattern: /listening|Serving|bind/i, required: false }];
  }

  get protectionPatterns() {
    return [/rate.?limit|quota exceeded/i];
  }

  async spawnSpec() {
    this.failurePatterns = [/panic:/, /FATAL/];
    this.stopCommand = null;
    const dir = this.freshWorkDir();
    const bin = await download(this.spec.url, join(this.cacheDir, 'proxies', `gate-${this.spec.version}`), { sha256: this.spec.sha256 });
    const local = join(dir, 'gate');
    copyFileSync(bin, local);
    chmodSync(local, 0o755);
    writeFileSync(join(dir, 'config.yml'), this.lite ? this.liteConfig() : this.fullConfig());
    return {
      command: local,
      args: [],
      // Gate reads config.yml from the working directory; GODEBUG off, Go runtime defaults.
      env: {},
    };
  }

  fullConfig() {
    const servers = Object.entries(this.backends)
      .map(([name, port]) => `      ${name}: 127.0.0.1:${port}`)
      .join('\n');
    const order = Object.keys(this.backends)
      .map((s) => `"${s}"`)
      .join(', ');
    return `# Generated by bench/src/proxies/gate.js (full)
config:
  bind: 127.0.0.1:${this.port}
  onlineMode: false
  forwarding:
    mode: velocity
    velocitySecret: ${this.secret}
  compression:
    threshold: ${this.compressionThreshold}
    level: ${this.compressionLevel}
  connectionTimeout: 5s
  readTimeout: 30s
  servers:
${servers}
  try: [${order}]
  quota:
    connections:
      enabled: false
    logins:
      enabled: false
  packetLimiter:
    enabled: false
`;
  }

  liteConfig() {
    // Lite routes every virtual host to the default backend: the bots all target one host.
    return `# Generated by bench/src/proxies/gate.js (lite)
config:
  bind: 127.0.0.1:${this.port}
  # Per-/24 connection and login quotas are on by default and throttle a load generator on one
  # address to a burst of 10: off, as for the full proxy and every other proxy here.
  quota:
    connections:
      enabled: false
    logins:
      enabled: false
  lite:
    enabled: true
    routes:
      - host: ["*"]
        backend: ["127.0.0.1:${this.backends[this.defaultBackend]}"]
        cachePingTTL: -1
`;
  }
}
