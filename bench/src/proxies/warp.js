// Warp: the proxy under test. Downloaded as the published release jar (or a local jar passed with
// --warp-jar), launched on Java 25 with the identical headline JVM flags, modern (Velocity) player
// forwarding, and its compression and transport loggers raised to debug so the start-up log states
// which compressor and transport actually loaded (the fairness check in base.js reads those lines).
import { copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { JVM_HEADLINE_FLAGS } from './index.js';
import { Proxy } from './base.js';
import { download, findJava } from '../reuse.js';

export class WarpProxy extends Proxy {
  get forwarding() {
    return 'modern';
  }

  nativeCheckDefs() {
    return [
      { label: 'compression', pattern: /Compression: libdeflate/, required: true },
      { label: 'transport', pattern: /Using epoll native transport/, required: true },
    ];
  }

  async spawnSpec() {
    this.nativeChecks = this.nativeCheckDefs();
    this.stopCommand = null;
    const dir = this.freshWorkDir();
    const jar = this.localJar ?? (await download(this.spec.url, join(this.cacheDir, 'proxies', `warp-${this.spec.version}.jar`), { sha256: this.spec.sha256 }));
    copyFileSync(jar, join(dir, 'warp.jar'));
    writeFileSync(join(dir, 'warp.conf'), this.config());
    const java = await findJava(this.spec.java, this.cacheDir);
    return {
      command: java,
      args: [
        ...JVM_HEADLINE_FLAGS,
        '--sun-misc-unsafe-memory-access=allow',
        '-jar',
        'warp.jar',
      ],
      env: { WARP_FORWARDING_SECRET: this.secret },
    };
  }

  config() {
    const servers = Object.entries(this.backends)
      .map(([name, port]) => `  ${name} {\n    address = "127.0.0.1:${port}"\n  }`)
      .join('\n');
    const order = Object.keys(this.backends);
    return `# Generated by bench/src/proxies/warp.js
bind = "127.0.0.1:${this.port}"
online-mode = false
servers {
${servers}
}
default-server = "${this.defaultBackend}"
fallback-order = [${order.map((s) => `"${s}"`).join(', ')}]
forwarding {
  mode = "velocity"
}
compression {
  threshold = ${this.compressionThreshold}
  level = ${this.compressionLevel}
  passthrough = true
}
logging {
  levels {
    "dev.warp.proxy.compression.Compression" = debug
    "dev.warp.proxy.WarpServer" = debug
  }
}
`;
  }
}
