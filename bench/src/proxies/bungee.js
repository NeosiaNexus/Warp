// BungeeCord. Downloaded from the SpigotMC Jenkins (no official checksum is published, so the hash
// in versions.json is one we computed and pin ourselves), launched on Java 25 with the identical
// headline JVM flags, legacy IP forwarding (its only forwarding), and per-IP connection throttling
// off. BungeeCord prints the native cipher and compressor it loaded; the fairness check reads those.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { JVM_HEADLINE_FLAGS } from './index.js';
import { Proxy } from './base.js';
import { download, findJava } from '../reuse.js';

export class BungeeProxy extends Proxy {
  get forwarding() {
    return 'legacy';
  }

  async spawnSpec() {
    this.nativeChecks = [
      { label: 'compression', pattern: /native (zlib|compression|code)/i, required: false },
      { label: 'cipher', pattern: /native (cipher|mbed)/i, required: false },
    ];
    this.failurePatterns = [/Could not (bind|start)/i];
    this.stopCommand = 'end';
    const dir = this.freshWorkDir();
    const jar = await download(this.spec.url, join(this.cacheDir, 'proxies', `bungeecord-${this.spec.version}.jar`), { sha256: this.spec.sha256 });
    mkdirSync(join(dir, 'plugins'), { recursive: true });
    writeFileSync(join(dir, 'config.yml'), this.config());
    const java = await findJava(this.spec.java, this.cacheDir);
    return {
      command: java,
      args: [...JVM_HEADLINE_FLAGS, '-jar', jar],
      env: {},
    };
  }

  config() {
    const servers = Object.entries(this.backends)
      .map(([name, port]) => `  ${name}:\n    address: 127.0.0.1:${port}\n    motd: bench\n    restricted: false`)
      .join('\n');
    const priorities = Object.keys(this.backends)
      .map((s) => `    - ${s}`)
      .join('\n');
    return `# Generated by bench/src/proxies/bungee.js
online_mode: false
ip_forward: true
network_compression_threshold: ${this.compressionThreshold}
connection_throttle: -1
connection_throttle_limit: 0
remote_ping_cache: -1
log_pings: false
log_commands: false
player_limit: -1
timeout: 30000
listeners:
- host: 127.0.0.1:${this.port}
  query_enabled: false
  motd: bench
  max_players: 100000
  force_default_server: false
  bind_local_address: true
  ping_passthrough: false
  priorities:
${priorities}
servers:
${servers}
`;
  }
}
