// The sound event ids of the clients that name a sound following an entity by its id: 1.14, which
// added the Entity Sound Effect packet, to 1.19.2 (1.19.3 lets the server name the sound instead).
// Read from Mojang's own data generator (`reports/registries.json`, the `minecraft:sound_event`
// registry), one list per protocol, and written as one table Warp loads at run time
// (tools/sound-events.js): the first list whole, every other one as the edits that make it from
// the previous one, so that 19 lists of about 1,300 names stay a few thousand lines.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The registry the ids come from, as the data generator names it. */
export const SOUND_REGISTRY = 'minecraft:sound_event';

/**
 * Reads the sound event names of a release from its data generator's reports, in id order.
 * @param {string} reports the reports directory
 * @returns {string[]} the names without their `minecraft:` namespace, at their id
 */
export function soundEvents(reports) {
  const registries = JSON.parse(readFileSync(join(reports, 'registries.json'), 'utf8'));
  const entries = registries[SOUND_REGISTRY]?.entries;
  if (!entries) throw new Error(`registries.json has no ${SOUND_REGISTRY} registry`);
  const names = [];
  for (const [name, entry] of Object.entries(entries)) {
    const id = entry?.protocol_id;
    if (!Number.isInteger(id) || id < 0) throw new Error(`${name} has no protocol id`);
    if (names[id] !== undefined) throw new Error(`${name} and ${names[id]} share id ${id}`);
    if (!name.startsWith('minecraft:')) throw new Error(`${name} is not a minecraft sound`);
    names[id] = name.slice('minecraft:'.length);
  }
  for (let id = 0; id < names.length; id++) {
    if (names[id] === undefined) throw new Error(`no sound has id ${id}`);
  }
  return names;
}

/**
 * The edits that turn `from` into `to`, applied in order to a copy of `from`: `{ op: '+', at, name }`
 * inserts `name` at index `at`, `{ op: '-', at }` removes the entry at `at`. The fewest edits keep
 * the longest common subsequence in place.
 */
export function edits(from, to) {
  const n = from.length;
  const m = to.length;
  // lcs[i][j]: the longest common subsequence of from[i..] and to[j..], one row per i.
  const lcs = Array.from({ length: n + 1 }, () => new Uint16Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      lcs[i][j] = from[i] === to[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
    }
  }
  const result = [];
  let i = 0;
  let j = 0;
  let at = 0; // position in the list being edited
  while (i < n || j < m) {
    if (i < n && j < m && from[i] === to[j]) {
      i++;
      j++;
      at++;
    } else if (j < m && (i === n || lcs[i][j + 1] >= lcs[i + 1][j])) {
      result.push({ op: '+', at, name: to[j] });
      j++;
      at++;
    } else {
      result.push({ op: '-', at });
      i++;
    }
  }
  return result;
}

/** Applies {@link edits} to a copy of `list`. */
export function applyEdits(list, changes) {
  const result = [...list];
  for (const change of changes) {
    if (change.op === '+') result.splice(change.at, 0, change.name);
    else result.splice(change.at, 1);
  }
  return result;
}

/**
 * The table Warp loads, from each protocol's list, oldest protocol first.
 * @param {{protocol: number, version: string, names: string[]}[]} lists
 */
export function table(lists) {
  const lines = [
    '# Sound event ids of the clients that name a sound following an entity by its id (1.14 to',
    "# 1.19.2), from Mojang's data generator (reports/registries.json, the minecraft:sound_event",
    '# registry). Generated by e2e/tools/sound-events.js (npm run sound-events): regenerate it, do not',
    '# edit it.',
    '#',
    '# "protocol P" starts the list of protocol P, one name a line, whose ids count from 0; "protocol P',
    '# from Q" starts from the list of Q and edits it in order: "+I name" inserts name at id I, "-I"',
    '# removes the name at id I. Names have no "minecraft:" namespace.',
  ];
  let previous = null;
  for (const { protocol, version, names } of lists) {
    if (previous === null) {
      lines.push(`protocol ${protocol} (${version})`, ...names);
    } else {
      lines.push(`protocol ${protocol} (${version}) from ${previous.protocol}`);
      for (const change of edits(previous.names, names)) {
        lines.push(change.op === '+' ? `+${change.at} ${change.name}` : `-${change.at}`);
      }
    }
    previous = { protocol, names };
  }
  return `${lines.join('\n')}\n`;
}

/**
 * What the tests check the table against, straight from each report: the number of sounds, a
 * SHA-256 of every name in id order, and the id of a few sounds.
 * @param {{protocol: number, version: string, names: string[]}[]} lists
 * @param {string[]} sampled names to give the id of, where the protocol has them
 */
export function samples(lists, sampled) {
  const lines = [
    '# What SoundEventIdsTest checks the sound event table against, read straight from each',
    "# release's reports/registries.json, independently of the table's encoding: \"<protocol> count",
    '# <n>", "<protocol> sha256 <hex>" of the names in id order, one per line, and "<protocol> id',
    '# <name> <id>". Generated by e2e/tools/sound-events.js with the table.',
  ];
  for (const { protocol, names } of lists) {
    lines.push(`${protocol} count ${names.length}`, `${protocol} sha256 ${digest(names)}`);
    for (const name of sampled) {
      const id = names.indexOf(name);
      if (id >= 0) lines.push(`${protocol} id ${name} ${id}`);
    }
    // The first and the last sound, whatever they are.
    lines.push(`${protocol} id ${names[0]} 0`, `${protocol} id ${names.at(-1)} ${names.length - 1}`);
  }
  return `${lines.join('\n')}\n`;
}

/** SHA-256 of the names, each followed by a line feed. */
export function digest(names) {
  return createHash('sha256').update(names.map((name) => `${name}\n`).join('')).digest('hex');
}
